function read(relative) {
  const absolute = path.join(root, relative);
  if (!fs.existsSync(absolute)) throw new Error(`No existe ${relative}. Ejecuta el instalador desde la raíz del repositorio.`);
  return fs.readFileSync(absolute, 'utf8');
}

const states = files.map((file) => ({ file, current: read(file.relative) }));
if (states.every(({ current }) => current.includes(marker))) {
  console.log('Phase 4H.2.5 ya estaba instalada. No se realizaron cambios.');
  process.exit(0);
}
for (const { file, current } of states) {
  if (!current.includes(marker) && !current.includes(file.prerequisite)) {
    throw new Error(`${file.relative} no contiene la base 4H.2.4 esperada. No se sobrescribe una versión desconocida.`);
  }
}

const stamp = new Date().toISOString().replace(/[:.]/g, '-');
const backupDir = path.join(root, '_gc_backups', `phase4h2-5-profile-link-review-${stamp}`);
fs.mkdirSync(backupDir, { recursive: true });

for (const { file, current } of states) {
  if (current.includes(marker)) continue;
  const output = Buffer.from(file.base64, 'base64');
  const digest = crypto.createHash('sha256').update(output).digest('hex');
  if (digest !== file.sha256) throw new Error(`Payload corrupto para ${file.relative}.`);
  const source = path.join(root, file.relative);
  const backup = path.join(backupDir, file.relative);
  fs.mkdirSync(path.dirname(backup), { recursive: true });
  fs.copyFileSync(source, backup);
  const temporary = `${source}.phase4h2-5.tmp`;
  fs.writeFileSync(temporary, output);
  fs.renameSync(temporary, source);
  console.log(`Actualizado: ${file.relative}`);
}

console.log(`Backup: ${path.relative(root, backupDir)}`);
console.log('Phase 4H.2.5 instalada. Ejecuta npm run quality y npm run build.');

